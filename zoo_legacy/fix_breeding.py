lines = [
    "from PyQt6.QtWidgets import QDialog, QVBoxLayout, QHBoxLayout, QComboBox, QPushButton, QLabel, QProgressBar, QMessageBox",
    "from PyQt6.QtCore import Qt, QTimer",
    "from models.animal import Lion, Tiger",
    "from models.genetics import Gene, GeneticCode",
    "",
    "class BreedingDialog(QDialog):",
    "    def __init__(self, db_manager, parent=None):",
    "        super().__init__(parent)",
    "        self.db = db_manager",
    "        self.setWindowTitle('Лаборатория скрещивания')",
    "        self.resize(500, 300)",
    "        self.setModal(True)",
    "        layout = QVBoxLayout()",
    "        layout.setSpacing(15)",
    "        title = QLabel('Выберите пару для скрещивания')",
    "        title.setStyleSheet('font-size: 16px; font-weight: bold; color: #3B82F6;')",
    "        title.setAlignment(Qt.AlignmentFlag.AlignCenter)",
    "        layout.addWidget(title)",
    "        combo_layout = QHBoxLayout()",
    "        self.father_combo = QComboBox()",
    "        self.mother_combo = QComboBox()",
    "        self.father_combo.setMinimumWidth(200)",
    "        self.mother_combo.setMinimumWidth(200)",
    "        self.load_animals_to_combos()",
    "        combo_layout.addWidget(QLabel('Отец:'))",
    "        combo_layout.addWidget(self.father_combo)",
    "        combo_layout.addWidget(QLabel('Мать:'))",
    "        combo_layout.addWidget(self.mother_combo)",
    "        layout.addLayout(combo_layout)",
    "        self.progress_bar = QProgressBar()",
    "        self.progress_bar.setVisible(False)",
    "        self.progress_bar.setStyleSheet('QProgressBar { border: 2px solid grey; border-radius: 5px; text-align: center; } QProgressBar::chunk { background-color: #10B981; }')",
    "        layout.addWidget(self.progress_bar)",
    "        self.status_label = QLabel('')",
    "        self.status_label.setAlignment(Qt.AlignmentFlag.AlignCenter)",
    "        layout.addWidget(self.status_label)",
    "        btn_layout = QHBoxLayout()",
    "        self.btn_breed = QPushButton('ЗАПУСТИТЬ РАЗВЕДЕНИЕ')",
    "        self.btn_breed.setStyleSheet('background-color: #8B5CF6; color: white; padding: 12px; font-weight: bold; border-radius: 5px;')",
    "        self.btn_breed.clicked.connect(self.start_breeding)",
    "        btn_cancel = QPushButton('Отмена')",
    "        btn_cancel.setStyleSheet('background-color: #EF4444; color: white; padding: 12px; font-weight: bold; border-radius: 5px;')",
    "        btn_cancel.clicked.connect(self.reject)",
    "        btn_layout.addWidget(self.btn_breed)",
    "        btn_layout.addWidget(btn_cancel)",
    "        layout.addLayout(btn_layout)",
    "        self.setLayout(layout)",
    "        self.timer = QTimer()",
    "        self.timer.timeout.connect(self.update_progress)",
    "        self.progress_value = 0",
    "",
    "    def load_animals_to_combos(self):",
    "        animals = self.db.get_all_animals()",
    "        self.father_combo.clear()",
    "        self.mother_combo.clear()",
    "        self.father_combo.addItem('Выберите...', None)",
    "        self.mother_combo.addItem('Выберите...', None)",
    "        for animal in animals:",
    "            display_name = f'{animal[1]} ({animal[2]}, {animal[3]} лет)'",
    "            self.father_combo.addItem(display_name, animal[0])",
    "            self.mother_combo.addItem(display_name, animal[0])",
    "",
    "    def start_breeding(self):",
    "        father_id = self.father_combo.currentData()",
    "        mother_id = self.mother_combo.currentData()",
    "        if not father_id or not mother_id:",
    "            QMessageBox.warning(self, 'Ошибка', 'Пожалуйста, выберите обоих родителей!')",
    "            return",
    "        if father_id == mother_id:",
    "            QMessageBox.warning(self, 'Ошибка', 'Нельзя скрестить животное само с собой!')",
    "            return",
    "        f_species, f_genetics = self.db.get_animal_genetics(father_id)",
    "        m_species, m_genetics = self.db.get_animal_genetics(mother_id)",
    "        if f_species != m_species:",
    "            QMessageBox.warning(self, 'Несовместимость', f'{f_species} и {m_species} не могут быть скрещены. Выберите пару одного вида.')",
    "            return",
    "        self.btn_breed.setEnabled(False)",
    "        self.progress_bar.setVisible(True)",
    "        self.progress_value = 0",
    "        self.progress_bar.setValue(0)",
    "        self.status_label.setText('Анализируем генетическую совместимость...')",
    "        self.timer.start(50)",
    "",
    "    def update_progress(self):",
    "        self.progress_value += 2",
    "        self.progress_bar.setValue(self.progress_value)",
    "        if self.progress_value == 30:",
    "            self.status_label.setText('Рассчитываем комбинацию генов...')",
    "        elif self.progress_value == 60:",
    "            self.status_label.setText('Проверяем вероятность мутаций...')",
    "        elif self.progress_value == 90:",
    "            self.status_label.setText('Инкубация...')",
    "        if self.progress_value >= 100:",
    "            self.timer.stop()",
    "            self.finish_breeding()",
    "",
    "    def finish_breeding(self):",
    "        father_id = self.father_combo.currentData()",
    "        f_species, f_genetics = self.db.get_animal_genetics(father_id)",
    "        try:",
    "            father_genes = GeneticCode()",
    "            mother_genes = GeneticCode()",
    "            for g_name, g_val in f_genetics.items():",
    "                father_genes.add_gene(Gene(g_name, g_val[0].upper(), g_val[1].lower()))",
    "            m_species, m_genetics = self.db.get_animal_genetics(self.mother_combo.currentData())",
    "            for g_name, g_val in m_genetics.items():",
    "                mother_genes.add_gene(Gene(g_name, g_val[0].upper(), g_val[1].lower()))",
    "            offspring_genetics = father_genes.combine(mother_genes)",
    "            offspring_genetics.mutate_all()",
    "            if f_species == 'Лев':",
    "                offspring = Lion('Детёныш Льва', 0, offspring_genetics)",
    "            else:",
    "                offspring = Tiger('Детёныш Тигра', 0, offspring_genetics)",
    "            offspring.feed(20)",
    "            self.db.add_animal(offspring)",
    "            self.status_label.setText('Успешно!')",
    "            QMessageBox.information(self, 'Потомство получено!', f'Родился новый {offspring.get_species()}!\\nГенетический код: {offspring.genetic_code}')",
    "            self.accept()",
    "        except Exception as e:",
    "            self.status_label.setText('Ошибка')",
    "            QMessageBox.critical(self, 'Ошибка', f'Не удалось создать потомство: {e}')",
    "            self.btn_breed.setEnabled(True)",
    "            self.progress_bar.setVisible(False)",
]

with open('ui/breeding_dialog.py', 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))

